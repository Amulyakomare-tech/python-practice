"""
DATA TYPES IN PYTHON
"""

# -------------------
# 🔹 CONCEPT
# -------------------
# Common data types:
# int, float, str, bool

# -------------------
# 🔹 EXAMPLES
# -------------------

num = 10              # int
price = 99.99         # float
text = "Python"       # string
is_active = False     # boolean

print(type(num))
print(type(price))
print(type(text))
print(type(is_active))

# String operations
first = "Hello"
second = "World"
print(first + " " + second)

# Boolean example
print(10 > 5)
print(10 == 3)


# -------------------
# 🔹 PRACTICE
# -------------------

marks = 85
percentage = 92.5
result = True

print("Marks type:", type(marks))
print("Percentage type:", type(percentage))
print("Result type:", type(result))
