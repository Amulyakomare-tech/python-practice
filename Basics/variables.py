"""
VARIABLES IN PYTHON
"""

# -------------------
# 🔹 CONCEPT
# -------------------
# Variable is a container used to store data.
# Python is dynamically typed (type define karna nahi padta).

# -------------------
# 🔹 EXAMPLES
# -------------------

name = "Amulya"
age = 18
height = 5.4
is_student = True

print(name)
print(age)
print(height)
print(is_student)

# Reassigning variable
age = 19
print("Updated age:", age)

# Multiple assignment
a, b, c = 1, 2, 3
print(a, b, c)


# -------------------
# 🔹 PRACTICE
# -------------------

city = "banglore"
